#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "songpack/PreviewPage.h"

static FILE* open_output(const char* dir, const char* name)
{
    char path[2048];
    if (snprintf(path, sizeof(path), "%s/%s", dir, name) >= (int)sizeof(path))
    {
        return NULL;
    }
    FILE* f = fopen(path, "wb");
    if (!f)
    {
        perror(path);
    }
    return f;
}

static int write_page(const char* dir, const char* name, const Song* song, const char* origin)
{
    Buffer page = {0};
    if (!preview_page_render(song, origin, &page))
    {
        buffer_free(&page);
        return 0;
    }
    FILE* file = open_output(dir, name);
    int ok = file != NULL;
    if (file)
    {
        ok = fwrite(page.data, 1, page.len, file) == page.len;
        if (fclose(file))
        {
            ok = 0;
        }
    }
    buffer_free(&page);
    return ok;
}

static void
write_embedded_bytes(FILE* header, const char* prefix, int index, const char* text, size_t length)
{
    fprintf(header, "static const unsigned char %s_%d[] = {", prefix, index);
    for (size_t i = 0; i < length; ++i)
    {
        fprintf(header, "%u,", (unsigned char)text[i]);
    }
    fprintf(header, "0};\n");
}

static void write_embedded_table(FILE* header, const char* name, const char* prefix, int count)
{
    fprintf(header, "static const char *const %s[] = {", name);
    for (int i = 0; i < count; ++i)
    {
        fprintf(header, "(const char *)%s_%d,", prefix, i);
    }
    fprintf(header, "};\n");
}

int main(int argc, char** argv)
{
    if (argc < 5)
    {
        fprintf(stderr, "Usage: songpack SITE_DIR GENERATED_DIR ORIGIN SONG.yaml...\n");
        return 1;
    }
    FILE* header = open_output(argv[2], "embedded.h");
    if (!header)
    {
        return 1;
    }
    fprintf(header,
            "/* Generated from song YAML by the C songpack tool. */\n#ifndef "
            "EMBEDDED_H\n#define EMBEDDED_H\n");
    char** slugs = calloc((size_t)argc, sizeof(*slugs));
    if (!slugs)
    {
        return 1;
    }
    for (int i = 4; i < argc; ++i)
    {
        FILE* in = fopen(argv[i], "rb");
        Song* song = calloc(1, sizeof(*song));
        char *text = malloc(MAX_IMPORT + 1), error[256];
        if (!in || !song || !text)
        {
            fprintf(stderr, "Unable to read %s\n", argv[i]);
            return 1;
        }
        size_t len = fread(text, 1, MAX_IMPORT + 1, in);
        int io_error = ferror(in);
        fclose(in);
        if (io_error || !song_parse(song, text, len, error, sizeof(error)))
        {
            fprintf(stderr, "%s: %s\n", argv[i], io_error ? "Read error" : error);
            return 1;
        }
        if (song->artwork[0] && !song->color[0])
        {
            fprintf(stderr,
                    "%s: Artwork needs a cached color. Import and export the YAML in the editor "
                    "first.\n",
                    argv[i]);
            return 1;
        }
        for (int j = 4; j < i; ++j)
        {
            if (!strcmp(slugs[j], song->slug))
            {
                fprintf(stderr, "Duplicate slug: %s\n", song->slug);
                return 1;
            }
        }
        slugs[i] = malloc(strlen(song->slug) + 1);
        if (!slugs[i])
        {
            return 1;
        }
        strcpy(slugs[i], song->slug);
        /* Filesystem layout is generated by CMake from filenames. Keep slugs in sync. */
        const char* base = strrchr(argv[i], '/');
        base = base ? base + 1 : argv[i];
        char expected[96];
        snprintf(expected, sizeof(expected), "%s.yaml", song->slug);
        if (strcmp(base, expected))
        {
            fprintf(stderr, "Filename must match slug: %s\n", expected);
            return 1;
        }
        write_embedded_bytes(header, "song", i - 4, text, len);
        write_embedded_bytes(header, "title", i - 4, song_title(song), strlen(song_title(song)));
        write_embedded_bytes(header, "slug", i - 4, song->slug, strlen(song->slug));
        char name[192];
        snprintf(name, sizeof(name), "%s.html", song->slug);
        if (!write_page(argv[1], name, song, argv[3]))
        {
            return 1;
        }
        snprintf(name, sizeof(name), "s/%s/index.html", song->slug);
        if (!write_page(argv[1], name, song, argv[3]))
        {
            return 1;
        }
        free(text);
        free(song);
    }
    if (!write_page(argv[1], "index.html", NULL, argv[3]))
    {
        return 1;
    }
    write_embedded_table(header, "embedded_songs", "song", argc - 4);
    write_embedded_table(header, "embedded_titles", "title", argc - 4);
    write_embedded_table(header, "embedded_slugs", "slug", argc - 4);
    fprintf(header, "#define SONG_COUNT %d\n#endif\n", argc - 4);
    if (fclose(header))
    {
        return 1;
    }
    for (int i = 4; i < argc; ++i)
    {
        free(slugs[i]);
    }
    free(slugs);
    printf("Packed %d songs and generated static preview pages.\n", argc - 4);
    return 0;
}
